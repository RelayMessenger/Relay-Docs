#!/usr/bin/env node
// Inlines the introduction hero art so the landing page ships its SVGs in the
// page instead of fetching ten image files (2026-09-14). Reads every
// images/hero/*.svg and writes snippets/hero-art.jsx, a Mintlify snippet that
// exports one HeroArt component. `--check` fails when the snippet is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "images", "hero");
const TARGET = join(ROOT, "snippets", "hero-art.jsx");

export function collect() {
  const art = {};
  for (const file of readdirSync(SOURCE).filter((f) => f.endsWith(".svg")).sort()) {
    const dark = file.endsWith("-dark.svg");
    const name = file.replace(/(-dark)?\.svg$/, "");
    const svg = readFileSync(join(SOURCE, file), "utf8").trim();
    if (!svg.startsWith("<svg")) throw new Error(`${file} is not an SVG document`);
    art[name] ??= {};
    art[name][dark ? "dark" : "light"] = svg;
  }
  for (const [name, schemes] of Object.entries(art)) {
    if (!schemes.light || !schemes.dark) throw new Error(`${name} needs both a light and a dark SVG`);
  }
  return art;
}

export function render(art) {
  // Mintlify evaluates each snippet export on its own, so the component must
  // carry its data; a sibling `export const` is not in scope at render time.
  // Tailwind variants inside a snippet are rewritten and mangled, so the
  // light/dark switch is plain CSS in style.css (.hero-art-light/-dark).
  return `// Generated by scripts/build-hero-inline.mjs from images/hero. Do not edit.
export const HeroArt = ({ name, className }) => {
  const heroArt = ${JSON.stringify(art, null, 2).replace(/\n/g, "\n  ")};
  return (
    <>
      <span
        className={["hero-art", "hero-art-light", className].filter(Boolean).join(" ")}
        dangerouslySetInnerHTML={{ __html: heroArt[name].light }}
      />
      <span
        className={["hero-art", "hero-art-dark", className].filter(Boolean).join(" ")}
        dangerouslySetInnerHTML={{ __html: heroArt[name].dark }}
      />
    </>
  );
};
`;
}

const expected = render(collect());
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(TARGET, "utf8"); } catch {}
  if (current !== expected) {
    console.error("snippets/hero-art.jsx is stale: run `npm run build:hero`");
    process.exit(1);
  }
  console.log(`hero art snippet matches ${Object.keys(collect()).length} sources`);
} else {
  writeFileSync(TARGET, expected);
  console.log(`wrote ${TARGET} (${expected.length} bytes)`);
}

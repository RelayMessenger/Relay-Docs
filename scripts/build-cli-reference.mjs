#!/usr/bin/env node
// Read help only. Never run a resource command without --help.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const require = createRequire(import.meta.url);
const cli = process.env.CLI_REFERENCE_BIN || require.resolve('relaymessenger/dist/cli.js');
const directory = path.join(root, 'integrations/cli/reference');
function help(args) {
  const result = spawnSync(process.execPath, [cli, '--agent', 'no', ...args], {
    cwd: root, encoding: 'utf8', env: { ...process.env, NO_COLOR: '1', FORCE_COLOR: '0' },
    timeout: 30000, maxBuffer: 1024 * 1024,
  });
  if (result.error || result.status !== 0) throw new Error(`Help failed for ${args.join(' ')}: ${result.error || result.stderr}`);
  return result.stdout.replace(/\r\n/g, '\n').trim();
}
function children(text, isRoot) {
  const names = [];
  let listing = false;
  for (const line of text.split('\n')) {
    if (/^(Commands|Get started|Every day|Everything else):$/.test(line)) { listing = true; continue; }
    if (listing && /^\S/.test(line)) listing = false;
    if (!listing) continue;
    if (isRoot && /^  auth,/.test(line)) names.push(...line.trim().split(/,\s*/));
    else {
      const match = line.match(/^  ([a-z][a-z-]*)(?:\s|$)/);
      if (match && match[1] !== 'help') names.push(match[1]);
    }
  }
  return [...new Set(names)];
}
const rootHelp = help(['--help']);
const exitCodes = help(['help', 'exit-codes']);
const globalOptions = rootHelp.split('\nOptions:\n')[1]?.split('\n\n')[0];
if (!globalOptions) throw new Error('Root help has no Options section');
const pages = new Map();
function collect(command) {
  const text = command.length ? help([...command, '--help']) : rootHelp;
  if (!text.startsWith('Usage: relaymessenger')) throw new Error(`Unexpected help for ${command.join(' ')}`);
  const slug = command.length ? command.join('-') : 'index';
  if (pages.has(slug)) throw new Error(`Duplicate command slug ${slug}`);
  const title = ['relaymessenger', ...command].join(' ');
  const options = text.split('\nOptions:\n')[1]?.split('\n\n')[0];
  const content = `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(`Command help for ${title}.`)}\nkeywords: ${JSON.stringify(['CLI', ...command, 'command reference'])}\n---\n\nRead the command's usage and options below.\n\n{/* Generated by scripts/build-cli-reference.mjs. Do not edit by hand. */}\n\n## Usage\n\n\`\`\`text captured-output\n${text}\n\`\`\`\n\n## Options\n\n${options ? `\`\`\`text captured-output\n${options}\n\`\`\`` : 'This command lists its subcommands in Usage.'}\n\n### Global options\n\n\`\`\`text captured-output\n${globalOptions}\n\`\`\`\n\n## Output\n\nThe Usage block is the captured help output, not a live API response. Resource commands describe their operation in that output.\n\n## Exit codes\n\n\`\`\`text captured-output\n${exitCodes}\n\`\`\`\n\n## See also\n\n- [CLI](/integrations/cli)\n- [Command reference](/integrations/cli/reference/index)\n`;
  pages.set(slug, content);
  if (command.at(-1) !== 'help') {
    for (const child of children(text, command.length === 0)) collect([...command, child]);
  }
}
collect([]);
// Commander supplies help at every group; one canonical page covers the help command.
collect(['help']);
const navigation = JSON.parse(readFileSync(path.join(root, 'docs.json'), 'utf8'));
let owner;
function find(value) {
  if (Array.isArray(value)) value.forEach(find);
  else if (value && typeof value === 'object') {
    if (value.group === 'CLI') owner = value;
    Object.values(value).forEach(find);
  }
}
find(navigation.navigation);
if (!owner) throw new Error('CLI navigation group not found');
const slugs = [...pages.keys()].sort();
const reference = { group: 'Command reference', expanded: false, pages: slugs.map(slug => `integrations/cli/reference/${slug}`) };
const current = owner.pages.findIndex(page => page?.group === reference.group);
if (current === -1) owner.pages.push(reference); else owner.pages[current] = reference;
const outputs = new Map([...pages].map(([slug, content]) => [path.join(directory, `${slug}.mdx`), content]));
outputs.set(path.join(root, 'docs.json'), JSON.stringify(navigation, null, 2) + '\n');
const stale = existsSync(directory) ? readdirSync(directory).filter(name => name.endsWith('.mdx') && !pages.has(name.slice(0, -4))) : [];
if (stale.length) throw new Error(`Stale generated pages require explicit removal: ${stale.join(', ')}`);
const changed = [...outputs].filter(([file, content]) => !existsSync(file) || readFileSync(file, 'utf8') !== content);
if (check && changed.length) {
  console.error(`CLI reference differs in ${changed.length} files:\n${changed.map(([file]) => path.relative(root, file)).join('\n')}`);
  process.exitCode = 1;
} else if (!check) {
  mkdirSync(directory, { recursive: true });
  for (const [file, content] of changed) writeFileSync(file, content);
}
console.log(`CLI reference: ${pages.size} pages; ${changed.length} ${check ? 'differences' : 'files written'}.`);
